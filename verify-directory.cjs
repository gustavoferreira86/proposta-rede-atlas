const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict');
const ctx=vm.createContext({});
vm.runInContext(fs.readFileSync('proposta/partners.js','utf8')+'\n'+fs.readFileSync('proposta/directory-model.js','utf8'),ctx);
const run=code=>vm.runInContext(code,ctx);
assert.equal(run('PARTNERS.length'),50);
assert.equal(run('COMPANIES.length'),41);
assert.equal(run('COMPANIES.flatMap(c=>c.units).length'),50);
assert.equal(run('new Set(COMPANIES.flatMap(c=>c.units.map(u=>u.id))).size'),50);
assert.equal(run("filterCompanies({query:'vital brasil'}).length"),1);
assert.equal(run("filterCompanies({query:'vital brasil'})[0].units.length"),6);
assert.equal(run("filterCompanies({query:'cepac'})[0].units.length"),3);
assert.equal(run("filterCompanies({query:'cepac',city:'Lorena'})[0].matchingUnits.length"),1);
assert.equal(run("filterCompanies({query:'vital brasil',city:'Guaratinguetá'})[0].matchingUnits.length"),3);
assert.equal(run("filterCompanies({query:'santa casa'}).length"),2);
assert.equal(run("filterCompanies({query:'vital pedregulho'})[0].matchingUnits[0].id"),22);
assert.equal(run("filterCompanies({query:'bio',city:'Potim'})[0].matchingUnits[0].id"),17);
assert.equal(run("filterCompanies({query:'cepac',city:'Lorena',category:'farmacia'}).length"),0);
assert.equal(run("filterCompanies({specialty:'Odontologia'}).flatMap(c=>c.matchingUnits).every(u=>u.specialties.includes('Odontologia'))"),true);
assert.equal(run("filterCompanies({query:'xyz-inexistente'}).length"),0);
console.log('14 checks passed: 41 companies, 50 preserved units, branch-specific filters, distinct hospitals kept separate.');
